"""Gate A byte-grammar examples; no acoustic solver or production API.

Run: python docs/research/og4-branch3-api-vectors.py
Golden inputs/bytes are fixed data, not regenerated by this command.
"""
from copy import deepcopy
from hashlib import sha256
import json
import math
from pathlib import Path
import struct

VERSION = "og4.canonical.binary.v1"
BACKEND = "og4.fixed.passive.branch3.pu.v1"
DOMAINS = {kind: f"morphoacoustics.og4.{kind}.v1"
           for kind in ("blueprint", "preparation", "observation")}
MAPPING = [[f"{organ}.{suffix}", organ, direction]
           for organ in "ABC" for suffix, direction in (("in", "inlet"), ("out", "outlet"))]


def encode(value):
    """E: encodes already validated contract data, NOT a schema validator."""
    if type(value) in (int, float):
        number = float(value)
        if not math.isfinite(number):
            raise ValueError("nonfinite number")
        return b"d" + struct.pack(">d", 0.0 if number == 0 else number)
    if type(value) is str:
        raw = value.encode("ascii")
        return b"s" + struct.pack(">I", len(raw)) + raw
    if type(value) is list:
        return b"l" + struct.pack(">I", len(value)) + b"".join(map(encode, value))
    if type(value) is dict and all(type(key) is str for key in value):
        keys = sorted(value, key=lambda key: key.encode("ascii"))
        return b"m" + struct.pack(">I", len(keys)) + b"".join(
            encode(key) + encode(value[key]) for key in keys)
    raise ValueError("unsupported encoding type")


def payload(kind, value):
    result = deepcopy(value)
    if kind == "blueprint":
        for field, key in (("organs", "id"), ("junctions", "id"), ("loads", "port")):
            result[field].sort(key=lambda row: row[key].encode("ascii"))
    elif kind == "observation":
        result.pop("observation_digest", None)
    return result


def canonical(kind, value):
    return DOMAINS[kind].encode("ascii") + b"\0" + encode(payload(kind, value))


def digest(kind, value):
    return "sha256:" + sha256(canonical(kind, value)).hexdigest()


def check(data):
    vectors = data["vectors"]
    for vector in vectors:
        raw = canonical(vector["kind"], vector["input"])
        assert raw.hex() == vector["canonical_hex"], vector["name"] + " bytes"
        assert digest(vector["kind"], vector["input"]) == vector["digest"], vector["name"] + " hash"
    by_name = {v["name"]: v for v in vectors}
    base = by_name["blueprint_matched"]["input"]
    permuted = deepcopy(base)
    permuted["organs"].reverse()
    permuted["loads"].reverse()
    assert digest("blueprint", permuted) == digest("blueprint", base)
    assert by_name["blueprint_fixed"]["digest"] == by_name["blueprint_fixed_negative_zero"]["digest"]
    assert by_name["blueprint_fixed"]["digest"] != by_name["blueprint_matched"]["digest"]
    # Every encoded leaf participates, including fields easy to accidentally omit.
    def leaves(value, path=()):
        if isinstance(value, dict):
            for key, child in value.items():
                yield from leaves(child, (*path, key))
        elif isinstance(value, list):
            for index, child in enumerate(value):
                yield from leaves(child, (*path, index))
        else:
            yield path, value
    checked_leaves = 0
    for name in ("blueprint_fixed", "preparation_matched", "observation_synthetic"):
        vector = by_name[name]
        for path, value in leaves(vector["input"]):
            changed = deepcopy(vector["input"])
            parent = changed
            for part in path[:-1]:
                parent = parent[part]
            parent[path[-1]] = value + "x" if type(value) is str else float(value) + 1.0
            assert digest(vector["kind"], changed) != vector["digest"], (name, path)
            checked_leaves += 1
    # Frequency order and repeated samples are semantic, not a set.
    obs = deepcopy(by_name["observation_synthetic"]["input"])
    for field in ("frequencies_hz", "pressure_pa", "volume_flow_m3_s", "mean_power_w", "diagnostics"):
        obs[field] = obs[field] * 2
    obs["frequencies_hz"] = [733, 997]
    changed = deepcopy(obs)
    changed["frequencies_hz"].reverse()
    assert digest("observation", obs) != digest("observation", changed)
    assert encode(-0.0) == encode(0) == encode(0.0)
    for invalid in (True, None, (733,), float("nan"), float("inf")):
        try:
            encode(invalid)
        except ValueError:
            pass
        else:
            raise AssertionError("invalid encoding accepted")
    print(f"PASS: {len(vectors)} fixed byte/hash vectors; {checked_leaves} leaf mutations; order/zero/type controls")


if __name__ == "__main__":
    check(json.loads(Path(__file__).with_name("og4-branch3-api-golden.json").read_text()))

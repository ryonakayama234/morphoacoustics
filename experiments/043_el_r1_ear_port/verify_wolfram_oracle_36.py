"""Verify complete WolframScript A1 full-grid regeneration against frozen 36-case oracle.

Usage: python experiments/043_el_r1_ear_port/verify_wolfram_oracle_36.py /tmp/el-r1-36-rebuilt.json
No Wolfram dependency at normal pytest runtime; this checks the independently regenerated bytes' numeric meaning.
"""
from __future__ import annotations

import json
import math
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
COLUMNS = (
    "length_m", "load_ratio", "frequency_hz", "transfer_real",
    "transfer_imag", "reflection_real", "reflection_imag",
    "normalized_formal_phasor_power",
)


def verify(candidate: dict, frozen: dict) -> None:
    if candidate["model"] != frozen["model"] or tuple(candidate["columns"]) != COLUMNS:
        raise AssertionError("model and column identity changed")
    rows = candidate["rows"]
    original = frozen["rows"]
    if len(rows) != 36 or len(original) != 36:
        raise AssertionError("must reproduce exactly 36 factorial records")
    for index, (a, b) in enumerate(zip(rows, original)):
        if len(a) != 8 or len(b) != 8:
            raise AssertionError(f"wrong column count at row {index}")
        for j, (x, y) in enumerate(zip(a, b)):
            if not isinstance(x, (int, float)) or not math.isfinite(x):
                raise AssertionError(f"nonfinite candidate at {index}:{j}")
            if not math.isclose(x, y, rel_tol=0, abs_tol=1e-11):
                raise AssertionError(f"oracle drift at {index}:{j}: {x} != {y}")


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: verify_wolfram_oracle_36.py regenerated.json")
    candidate = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    frozen = json.loads((HERE / "wolfram_oracle_36.json").read_text(encoding="utf-8"))
    verify(candidate, frozen)
    print("EL-R1 independent Wolfram 36-case regeneration: PASS")


if __name__ == "__main__":
    main()
